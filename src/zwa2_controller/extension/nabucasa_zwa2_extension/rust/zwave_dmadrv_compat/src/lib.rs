//! Runs the Z-Wave UART TX DMA on DMADRV.
//!
//! The ZPAL library's strong `LDMA_IRQHandler` only services its own channel and clears
//! every interrupt flag, so it is wrapped away in favour of DMADRV's handler, which an SDK
//! patch renames. ZPAL's TX-done callback is re-injected through a DMADRV transfer on the
//! same channel. I2C and SPI drivers built on DMADRV then work.
#![no_std]

use core::cell::Cell;
use core::ffi::{c_uint, c_void};
use core::ptr::{addr_of_mut, null_mut};

use critical_section::Mutex;

#[allow(
    non_camel_case_types,
    non_upper_case_globals,
    non_snake_case,
    dead_code
)]
mod bindings {
    include!(concat!(env!("OUT_DIR"), "/bindings.rs"));
}
use bindings::*;

// Generated by build.rs from the component's config
include!(concat!(env!("OUT_DIR"), "/config.rs"));

extern "C" {
    // ZPAL's, which no header declares
    fn __real_zpal_uart_utils_tx_transfer_start(
        data: *mut u8,
        length: usize,
        tx_cb: zpal_uart_transmit_done_t,
    );
    // DMADRV's LDMA_IRQHandler, renamed by the dmadrv-rename-ldma-irqhandler SDK patch
    fn dmadrv_LDMA_IRQHandler();
}

// ZPAL's TX-done callback is internal, so it is captured when ZPAL starts a transfer
static TX_CALLBACK: Mutex<Cell<zpal_uart_transmit_done_t>> = Mutex::new(Cell::new(None));

#[no_mangle]
pub extern "C" fn __wrap_zpal_uart_utils_tx_transfer_start(
    data: *mut u8,
    length: usize,
    tx_cb: zpal_uart_transmit_done_t,
) {
    critical_section::with(|cs| TX_CALLBACK.borrow(cs).set(tx_cb));
    unsafe { __real_zpal_uart_utils_tx_transfer_start(data, length, tx_cb) }
}

// Both LDMA_IRQHandlers are strong, so ZPAL's is wrapped away rather than weakened
#[no_mangle]
pub extern "C" fn __wrap_LDMA_IRQHandler() {
    unsafe { dmadrv_LDMA_IRQHandler() }
}

extern "C" fn tx_done(_channel: c_uint, _sequence_no: c_uint, _user_param: *mut c_void) -> bool {
    if let Some(callback) = critical_section::with(|cs| TX_CALLBACK.borrow(cs).get()) {
        unsafe { callback(null_mut()) };
    }
    false
}

// As of Simplicity SDK 2026.6.0, DMADRV is deprecated in favour of sl_dma_manager (it still
// works, delegating internally). This shim is deliberately built on DMADRV constructs to
// match the Z-Wave ZPAL and SPI/I2C drivers.
#[no_mangle]
pub extern "C" fn zwave_dmadrv_compat_init() -> sl_status_t {
    static mut DUMMY_DATA: u8 = 0;

    let result = unsafe { DMADRV_Init() };
    if result != ECODE_EMDRV_DMADRV_OK && result != ECODE_EMDRV_DMADRV_ALREADY_INITIALIZED {
        return SL_STATUS_FAIL;
    }

    // Allocate the Z-Wave LDMA channel before any other drivers
    let result = unsafe { DMADRV_AllocateChannelById(ZWAVE_LDMA_CHANNEL, null_mut()) };
    if result != ECODE_EMDRV_DMADRV_OK {
        return SL_STATUS_FAIL;
    }

    // A fake transfer installs the callback, which then persists indefinitely
    let dummy = addr_of_mut!(DUMMY_DATA) as *mut c_void;
    let result = unsafe {
        DMADRV_MemoryPeripheral(
            ZWAVE_LDMA_CHANNEL,
            0,
            dummy,
            dummy,
            false,
            1,
            ldmaCtrlSizeByte as DMADRV_DataSize_t,
            Some(tx_done),
            null_mut(),
        )
    };
    if result != ECODE_EMDRV_DMADRV_OK {
        return SL_STATUS_FAIL;
    }
    SL_STATUS_OK
}
